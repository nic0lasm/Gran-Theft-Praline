"""Turn a Tripo car master (one fused mesh) into a drivable car for Unreal.

Runs inside Blender (or the `bpy` Python module), no Unreal needed:

    blender -b -P tools/vehicles/prepare_vehicle.py -- \
        --master assets/tripo/v/V-01.glb --id V-01 --out assets/staging/vehicles

or `python -I tools/vehicles/prepare_vehicle.py -- ...` with `pip install bpy`.

Steps (docs/gameplay/vehicles.md, section 9.2):
1. Scale to the real length, front on +X, ground at Z=0, centred; bring
   the roof down to the real height above the wheel arches (masters are too tall).
2. Find the four wheels from the tyre contact patches and cut them out of
   the body (cylinder test around each wheel centre).
3. Take the greenhouse (above the belt line, not the roof) and copy it into
   four breakable glass panels (front, rear, left, right), pushed 4 mm
   outwards; the painted windows stay on the body underneath.
4. Keep the body whole under 1.4 M triangles (custom normals intact),
   wheels at 30 k each, Ultra total under 1.5 M; the M1 LODs are
   generated by Unreal's skeletal mesh reduction on import.
5. Skeleton: root, Phys_Wheel_FL/FR/BL/BR at the wheel centres, seat_driver.
6. Dent morph targets Dent_Front/Rear/Left/Right on the body.
7. Export SKM_<Name>.fbx, SM_<Name>_Glass_<Zone>.fbx, 4K textures,
   report.json and preview images.

Blender axes: X forward, Y left, Z up. Unreal's FBX import maps Blender Y
to Unreal -Y, so the left (driver) side ends up on Unreal -Y, as the C++
code expects.
"""

import argparse
import json
import math
import os
import sys

import bpy  # first: it makes bmesh and mathutils importable
import bmesh
import numpy as np
from mathutils import Matrix, Vector

HERE = os.path.dirname(os.path.abspath(__file__))
WHEEL_BONES = {("F", "L"): "Phys_Wheel_FL", ("F", "R"): "Phys_Wheel_FR",
               ("B", "L"): "Phys_Wheel_BL", ("B", "R"): "Phys_Wheel_BR"}
GLASS_ZONES = ("Front", "Rear", "Left", "Right")


# --- Helpers ----------------------------------------------------------------

def log(*args):
    print("[prepare_vehicle]", *args, flush=True)


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else sys.argv[1:]
    p = argparse.ArgumentParser()
    p.add_argument("--master", required=True)
    p.add_argument("--id", required=True, help="catalogue id, e.g. V-01")
    p.add_argument("--out", required=True, help="staging root")
    p.add_argument("--config", default=os.path.join(HERE, "vehicles.json"))
    p.add_argument("--no-export", action="store_true", help="analyse and preview only")
    p.add_argument("--preview", action="store_true", help="render preview images")
    return p.parse_args(argv)


def mesh_arrays(mesh):
    n_v, n_p = len(mesh.vertices), len(mesh.polygons)
    co = np.empty(n_v * 3, np.float32)
    mesh.vertices.foreach_get("co", co)
    tris = np.empty(n_p * 3, np.int32)
    mesh.polygons.foreach_get("vertices", tris)
    normals = np.empty(n_p * 3, np.float32)
    mesh.polygons.foreach_get("normal", normals)
    centers = np.empty(n_p * 3, np.float32)
    mesh.polygons.foreach_get("center", centers)
    return co.reshape(-1, 3), tris.reshape(-1, 3), normals.reshape(-1, 3), centers.reshape(-1, 3)


def face_uv_centres(mesh):
    uv = np.empty(len(mesh.loops) * 2, np.float32)
    mesh.uv_layers.active.data.foreach_get("uv", uv)
    return uv.reshape(-1, 3, 2).mean(axis=1)


def image_array(image):
    w, h = image.size
    px = np.empty(w * h * 4, np.float32)
    image.pixels.foreach_get(px)
    return px.reshape(h, w, 4)


def sample(img, uv):
    h, w = img.shape[:2]
    x = np.clip((uv[:, 0] % 1.0) * (w - 1), 0, w - 1).astype(np.int32)
    y = np.clip((uv[:, 1] % 1.0) * (h - 1), 0, h - 1).astype(np.int32)
    return img[y, x]


def material_images(material):
    """Base colour, metallic-roughness and normal images of a glTF-imported material."""
    found = {"base": None, "orm": None, "normal": None}
    for node in material.node_tree.nodes:
        if node.type != "TEX_IMAGE" or not node.image:
            continue
        for link in node.outputs["Color"].links:
            to = link.to_node
            if to.type == "BSDF_PRINCIPLED" and link.to_socket.name == "Base Color":
                found["base"] = node.image
            elif to.type == "SEPARATE_COLOR":
                found["orm"] = node.image
            elif to.type == "NORMAL_MAP":
                found["normal"] = node.image
    return found


def select_faces(obj, mask):
    sel = np.asarray(mask, dtype=bool)
    mesh = obj.data
    tris = np.empty(len(mesh.polygons) * 3, np.int32)
    mesh.polygons.foreach_get("vertices", tris)
    vsel = np.zeros(len(mesh.vertices), bool)
    vsel[tris.reshape(-1, 3)[sel].ravel()] = True
    mesh.vertices.foreach_set("select", vsel)
    mesh.polygons.foreach_set("select", sel)
    mesh.update()


def separate_selected(obj, name):
    """Moves the selected faces of obj into a new object and returns it."""
    part = duplicate_selected(obj, name)
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.delete(bm, geom=[f for f in bm.faces if f.select], context="FACES")
    bm.to_mesh(obj.data)
    bm.free()
    return part


def duplicate_selected(obj, name):
    copy = obj.copy()
    copy.data = obj.data.copy()
    copy.name = name
    copy.data.name = name
    bpy.context.collection.objects.link(copy)
    bm = bmesh.new()
    bm.from_mesh(copy.data)
    bmesh.ops.delete(bm, geom=[f for f in bm.faces if not f.select], context="FACES")
    bm.to_mesh(copy.data)
    bm.free()
    return copy


def decimate(obj, target_tris):
    tris = len(obj.data.polygons)
    if tris <= target_tris:
        return tris
    mod = obj.modifiers.new("decimate", "DECIMATE")
    mod.ratio = target_tris / tris
    mod.use_collapse_triangulate = True
    with bpy.context.temp_override(object=obj, active_object=obj, selected_objects=[obj]):
        bpy.ops.object.modifier_apply(modifier=mod.name)
    return len(obj.data.polygons)


def smoothstep(e0, e1, x):
    t = np.clip((x - e0) / max(e1 - e0, 1e-6), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def value_noise(p, seed, scale):
    """Cheap smooth 3D noise in [-1, 1] for crumpled dents."""
    rng = np.random.default_rng(seed)
    k = rng.normal(size=(6, 3)) * scale
    ph = rng.uniform(0, 2 * math.pi, size=6)
    return np.sum(np.sin(p @ k.T + ph), axis=1) / 3.0


# --- Steps ------------------------------------------------------------------

def import_master(path):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=path)
    meshes = [o for o in bpy.context.scene.objects if o.type == "MESH"]
    if len(meshes) != 1:
        raise SystemExit(f"expected one mesh in {path}, found {len(meshes)}")
    obj = meshes[0]
    for o in list(bpy.context.scene.objects):
        if o is not obj:
            bpy.data.objects.remove(o)
    obj.parent = None
    obj.data.transform(obj.matrix_world)
    obj.matrix_world.identity()
    obj.name = "Body"
    return obj


def detect_front_sign(co, height):
    """+1 if the bonnet is on +X. The cabin roof sits towards the rear on
    hatchbacks, saloons and vans alike, so the front is the other side."""
    top = co[co[:, 2] > 0.85 * height]
    centre = 0.5 * (co[:, 0].min() + co[:, 0].max())
    return -1.0 if top[:, 0].mean() > centre else 1.0


def normalise(obj, spec):
    co, *_ = mesh_arrays(obj.data)
    lo, hi = co.min(axis=0), co.max(axis=0)
    scale = spec["length_m"] / (hi[0] - lo[0])
    front = spec.get("front", "auto")
    sign = detect_front_sign(co, hi[2]) if front == "auto" else (1.0 if front == "+X" else -1.0)
    centre = Vector(((lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, lo[2]))
    # One matrix, so the master's custom normals are turned with the mesh.
    m = Matrix.Rotation(math.pi if sign < 0 else 0.0, 4, "Z") @ Matrix.Scale(scale, 4) @ Matrix.Translation(-centre)
    obj.data.transform(m)
    obj.data.update()
    return {"scale": float(scale), "front_auto_sign": float(sign), "front_setting": front}


def fit_height(obj, spec):
    """Brings the roof to the real height without touching the wheels.

    Tripo masters come out too tall at real length (~13 % on the Clio).
    Everything below the top of the wheel arches is kept as is, so wheels stay
    round and arches keep fitting them; the part above is compressed.
    """
    target = spec.get("height_m")
    if not target:
        return {}
    co, *_ = mesh_arrays(obj.data)
    roof = float(np.percentile(co[:, 2], 99.9))  # ignores aerials and roof bars
    keep = 2.15 * spec["wheel_radius_m"]
    if roof <= target or roof <= keep:
        return {"height_before_m": round(roof, 3), "height_fit": "none"}
    k = (target - keep) / (roof - keep)
    above = co[:, 2] > keep
    co[above, 2] = keep + (co[above, 2] - keep) * k
    obj.data.vertices.foreach_set("co", co.ravel())
    obj.data.update()
    return {"height_before_m": round(roof, 3), "height_after_m": round(target, 3), "upper_scale": round(float(k), 3)}


def find_wheels(co, spec):
    """Wheel centres from the tyre contact patches (vertices near the ground)."""
    radius = spec["wheel_radius_m"]
    width = spec["tyre_width_m"]
    ground = co[co[:, 2] < 0.035]
    wheels = {}
    for fb, sx in (("F", 1), ("B", -1)):
        for side, sy in (("L", 1), ("R", -1)):
            pts = ground[(np.sign(ground[:, 0]) == sx) & (np.sign(ground[:, 1]) == sy)]
            if len(pts) < 20:
                raise SystemExit(f"no tyre contact found for wheel {fb}{side} ({len(pts)} points)")
            x = float(np.median(pts[:, 0]))
            # Outer tyre wall: the outermost contact points.
            outer = float(np.percentile(np.abs(pts[:, 1]), 98))
            y = sy * (outer - width / 2)
            wheels[(fb, side)] = {"centre": [x, y, radius], "outer": outer, "contact_points": int(len(pts))}
    return wheels


def wheel_face_mask(centers, wheels, spec):
    radius = spec["wheel_radius_m"] * 1.03
    width = spec["tyre_width_m"]
    mask = np.zeros(len(centers), dtype=np.int8)
    for i, ((fb, side), w) in enumerate(sorted(wheels.items())):
        cx, cy, cz = w["centre"]
        r = np.hypot(centers[:, 0] - cx, centers[:, 2] - cz)
        ay = np.abs(centers[:, 1])
        inside = (r < radius) & (ay > w["outer"] - width - 0.03) & (ay < w["outer"] + 0.03) \
            & (np.sign(centers[:, 1]) == np.sign(cy))
        mask[inside & (mask == 0)] = i + 1
    return mask


def glass_face_mask(obj, centers, normals, spec, height):
    """Greenhouse faces: above the belt line, not the roof.

    Tripo paints the glass with the body's own reflections (same colour,
    roughness and metal as the paint on the Clio master), so the texture
    cannot tell glass from pillars. The whole greenhouse is used instead:
    pillars get a thin glass layer too, which reads as lacquer.
    """
    g = spec.get("glass", {})
    belt = g.get("belt_ratio", 0.64) * height
    return (centers[:, 2] > belt) & (centers[:, 2] < g.get("roof_ratio", 0.97) * height) \
        & (normals[:, 2] < g.get("max_up_normal", 0.9))


def in_polygon(px, py, poly):
    """Even-odd point-in-polygon test for arrays of points."""
    inside = np.zeros(len(px), bool)
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        cross = (y1 > py) != (y2 > py)
        with np.errstate(divide="ignore", invalid="ignore"):
            xi = (x2 - x1) * (py - y1) / (y2 - y1) + x1
        inside ^= cross & (px < xi)
    return inside


def outline_glass(centers, normals, greenhouse, outlines):
    """Glass zones from window outlines drawn on orthographic views of the
    master (vehicles.json): side windows in the side view (X, Z), mirrored
    for both sides; windscreen and rear window in the top view (X, Y)."""
    x, y, z = centers[:, 0], centers[:, 1], centers[:, 2]
    zone = np.full(len(centers), -1, np.int8)
    side = np.zeros(len(centers), bool)
    for poly in outlines.get("side", []):
        side |= in_polygon(x, z, poly)
    front = np.zeros(len(centers), bool)
    for poly in outlines.get("front", []):
        front |= in_polygon(x, y, poly)
    rear = np.zeros(len(centers), bool)
    for poly in outlines.get("rear", []):
        rear |= in_polygon(x, y, poly)
    nx, ny = normals[:, 0], normals[:, 1]
    zone[greenhouse & front & (nx > 0.15)] = 0
    zone[greenhouse & rear & (nx < -0.15)] = 1
    lateral = greenhouse & side & (np.abs(ny) > 0.35) & (zone < 0) \
        & (np.abs(y) < outlines.get("max_abs_y", 10.0))  # not the mirrors
    zone[lateral & (y > 0)] = 2
    zone[lateral & (y <= 0)] = 3
    return zone


def glass_zones(centers, normals, mask):
    zone = np.full(len(centers), -1, np.int8)
    nx, ny = normals[:, 0], normals[:, 1]
    front = mask & (nx > np.abs(ny)) & (centers[:, 0] > 0)
    rear = mask & (-nx > np.abs(ny)) & (centers[:, 0] < 0)
    left = mask & ~front & ~rear & (centers[:, 1] > 0)
    right = mask & ~front & ~rear & (centers[:, 1] <= 0)
    for i, m in enumerate((front, rear, left, right)):
        zone[m] = i
    return zone


def drop_small_islands(obj, mask, min_faces):
    """Keeps only connected regions of the mask with at least min_faces faces."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bm.faces.ensure_lookup_table()
    keep = np.zeros(len(mask), bool)
    seen = np.zeros(len(mask), bool)
    for f in bm.faces:
        if not mask[f.index] or seen[f.index]:
            continue
        stack, region = [f], []
        seen[f.index] = True
        while stack:
            cur = stack.pop()
            region.append(cur.index)
            for e in cur.edges:
                for nb in e.link_faces:
                    if mask[nb.index] and not seen[nb.index]:
                        seen[nb.index] = True
                        stack.append(nb)
        if len(region) >= min_faces:
            keep[region] = True
    bm.free()
    return keep


def push_along_normals(obj, distance):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bm.normal_update()
    for v in bm.verts:
        v.co += v.normal * distance
    bm.to_mesh(obj.data)
    bm.free()


def build_armature(wheels, spec):
    arm_data = bpy.data.armatures.new("Armature")
    arm = bpy.data.objects.new("Armature", arm_data)
    bpy.context.collection.objects.link(arm)
    bpy.context.view_layer.objects.active = arm
    bpy.ops.object.mode_set(mode="EDIT")
    root = arm_data.edit_bones.new("root")
    root.head, root.tail = (0, 0, 0), (0, 0, 0.3)
    for key, bone_name in WHEEL_BONES.items():
        c = Vector(wheels[key]["centre"])
        b = arm_data.edit_bones.new(bone_name)
        b.head, b.tail, b.parent = c, c + Vector((0, 0, 0.15)), root
    seat = arm_data.edit_bones.new("seat_driver")
    s = Vector(spec.get("seat_driver", [-0.15, 0.37, 0.45]))
    seat.head, seat.tail, seat.parent = s, s + Vector((0, 0, 0.1)), root
    bpy.ops.object.mode_set(mode="OBJECT")
    return arm


def add_dent_shape_keys(body, length, width, height, seed=11):
    """Dents on the body only: vertices of the wheel bones never move."""
    co, *_ = mesh_arrays(body.data)
    movable = np.ones(len(co), np.float32)
    root = body.vertex_groups.get("root")
    if root is not None:
        movable[:] = 0.0
        for v in body.data.vertices:
            for g in v.groups:
                if g.group == root.index and g.weight > 0.5:
                    movable[v.index] = 1.0
    body.shape_key_add(name="Basis", from_mix=False)
    half_l, half_w = length / 2, width / 2
    crumple = 0.5 + 0.5 * value_noise(co, seed, 9.0)

    def add(name, offsets):
        key = body.shape_key_add(name=name, from_mix=False)
        key.data.foreach_set("co", (co + offsets * movable[:, None]).ravel())
        key.value = 0.0  # exported as the FBX default weight: the car must start undamaged

    off = np.zeros_like(co)
    w = smoothstep(half_l * 0.55, half_l, co[:, 0]) * crumple
    off[:, 0] = -0.16 * w
    off[:, 2] = -0.03 * w * smoothstep(height * 0.3, height * 0.6, co[:, 2])
    add("Dent_Front", off)

    off = np.zeros_like(co)
    w = smoothstep(half_l * 0.6, half_l, -co[:, 0]) * crumple
    off[:, 0] = 0.12 * w
    add("Dent_Rear", off)

    for name, sign in (("Dent_Left", 1.0), ("Dent_Right", -1.0)):
        off = np.zeros_like(co)
        side = smoothstep(half_w * 0.6, half_w, sign * co[:, 1])
        along = 1.0 - smoothstep(half_l * 0.45, half_l * 0.9, np.abs(co[:, 0]))
        band = 1.0 - smoothstep(height * 0.55, height * 0.8, co[:, 2])
        off[:, 1] = -sign * 0.10 * side * along * band * crumple
        add(name, off)


def save_texture(image, path, size):
    img = image.copy()
    if img.size[0] > size:
        img.scale(size, size)
    img.filepath_raw = path
    img.file_format = "PNG"
    img.save()
    bpy.data.images.remove(img)


def export_fbx(objects, path, with_armature):
    for o in objects:
        if o.type == "MESH":
            o.data.polygons.foreach_set("use_smooth", np.ones(len(o.data.polygons), bool))
            o.data.update()
    bpy.ops.object.select_all(action="DESELECT")
    for o in objects:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.export_scene.fbx(
        filepath=path, use_selection=True, apply_unit_scale=True, apply_scale_options="FBX_SCALE_UNITS",
        object_types={"ARMATURE", "MESH"} if with_armature else {"MESH"},
        add_leaf_bones=False, use_armature_deform_only=False, bake_anim=False,
 mesh_smooth_type="OFF", use_tspace=True, path_mode="STRIP",
        axis_forward="-Z", axis_up="Y")


def render_preview(path, objects_colours):
    """Flat-coloured three-quarter view to check the cut (workbench, no textures)."""
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.display.shading.light = "STUDIO"
    scene.display.shading.color_type = "OBJECT"
    scene.render.resolution_x, scene.render.resolution_y = 1280, 720
    for o, colour in objects_colours:
        o.color = colour
    cam_data = bpy.data.cameras.new("cam")
    cam = bpy.data.objects.new("cam", cam_data)
    bpy.context.collection.objects.link(cam)
    scene.camera = cam
    for i, (loc, name) in enumerate((((6.5, 5.0, 2.6), "front_left"), ((-6.5, -5.0, 2.6), "rear_right"))):
        cam.location = loc
        direction = Vector((0, 0, 0.6)) - cam.location
        cam.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
        scene.render.filepath = f"{path}_{name}.png"
        bpy.ops.render.render(write_still=True)


# --- Main -------------------------------------------------------------------

def main():
    args = parse_args()
    with open(args.config) as f:
        spec = json.load(f)[args.id]
    name = spec["name"]
    out_dir = os.path.join(args.out, args.id)
    os.makedirs(os.path.join(out_dir, "textures"), exist_ok=True)
    report = {"id": args.id, "name": name, "master": os.path.basename(args.master)}

    body = import_master(args.master)
    report["source_tris"] = len(body.data.polygons)
    report.update(normalise(body, spec))
    report.update(fit_height(body, spec))
    co, tris, normals, centers = mesh_arrays(body.data)
    dims = co.max(axis=0) - co.min(axis=0)
    length, width, height = (float(d) for d in dims)
    report["dimensions_m"] = [round(length, 3), round(width, 3), round(height, 3)]
    log(name, "dimensions", report["dimensions_m"], "front sign", report["front_auto_sign"])

    wheels = find_wheels(co, spec)
    report["wheels"] = {f"{k[0]}{k[1]}": v for k, v in wheels.items()}
    wmask = wheel_face_mask(centers, wheels, spec)
    log("wheels", {f"{k[0]}{k[1]}": [round(c, 3) for c in v["centre"]] + [v["contact_points"], int((wmask == i + 1).sum())]
                   for i, (k, v) in enumerate(sorted(wheels.items()))})

    gmask = glass_face_mask(body, centers, normals, spec, height)
    gmask &= (wmask == 0)
    gspec = spec.get("glass", {})
    if gspec.get("mode") == "outline":
        zones = outline_glass(centers, normals, gmask, gspec)
        gmask = zones >= 0
    gmask = drop_small_islands(body, gmask, spec.get("glass", {}).get("min_island_faces", 400))
    if gspec.get("mode") == "outline":
        zones[~gmask] = -1
    else:
        zones = glass_zones(centers, normals, gmask)
    report["glass_faces"] = {z: int((zones == i).sum()) for i, z in enumerate(GLASS_ZONES)}
    log("glass faces", report["glass_faces"])

    # Glass panels: copies of the painted glass, pushed outwards.
    glass_objs = []
    for i, zone in enumerate(GLASS_ZONES):
        if not (zones == i).any():
            continue
        select_faces(body, zones == i)
        g = duplicate_selected(body, f"SM_{name}_Glass_{zone}")
        push_along_normals(g, 0.004)
        decimate(g, spec.get("glass_tris", 20000))
        glass_objs.append(g)

    # Wheels: cut out of the body.
    wheel_objs = {}
    for i, key in enumerate(sorted(wheels)):
        co_now, _, _, centers_now = mesh_arrays(body.data)
        mask_now = wheel_face_mask(centers_now, {key: wheels[key]}, spec) > 0
        if not mask_now.any():
            raise SystemExit(f"wheel {key} cut is empty")
        select_faces(body, mask_now)
        n_before = len(body.data.polygons)
        w = separate_selected(body, WHEEL_BONES[key])
        log("cut", key, int(mask_now.sum()), "->", len(w.data.polygons) if w else 0, "body", n_before, "->", len(body.data.polygons))
        wheel_objs[key] = w
        report["wheels"][f"{key[0]}{key[1]}"]["faces"] = len(w.data.polygons) if w else 0
    log("wheel faces", {k: v.get("faces") for k, v in report["wheels"].items()})

    if args.preview:
        colours = [(body, (0.75, 0.75, 0.78, 1))] + [(w, (0.9, 0.2, 0.1, 1)) for w in wheel_objs.values() if w] \
            + [(g, (0.1, 0.5, 0.95, 1)) for g in glass_objs]
        render_preview(os.path.join(out_dir, f"preview_{name}"), colours)

    if args.no_export:
        with open(os.path.join(out_dir, "report.json"), "w") as f:
            json.dump(report, f, indent=2)
        return

    # Budgets (art bible: vehicle exterior <= 1.5 M Ultra, 120 k M1).
    # The body keeps the master's custom normals when it fits the budget:
    # decimating recomputes normals from Tripo's slightly wavy surface and
    # shows ripples on the doors.
    report["body_tris"] = decimate(body, spec.get("body_tris", 1_400_000))
    for w in wheel_objs.values():
        if w:
            decimate(w, spec.get("wheel_tris", 30_000))

    images = material_images(body.data.materials[0])
    tex = {"BC": images["base"], "ORM": images["orm"], "N": images["normal"]}
    for suffix, img in tex.items():
        if img:
            save_texture(img, os.path.join(out_dir, "textures", f"T_{name}_{suffix}.png"), spec.get("texture_size", 4096))

    # Skinning: one mesh, one bone per part.
    arm = build_armature(wheels, spec)
    parts = [body] + [w for w in wheel_objs.values() if w]
    for part in parts:
        bone = "root" if part is body else part.name
        vg = part.vertex_groups.new(name=bone)
        vg.add(list(range(len(part.data.vertices))), 1.0, "REPLACE")
    bpy.ops.object.select_all(action="DESELECT")
    for part in parts:
        part.select_set(True)
    bpy.context.view_layer.objects.active = body
    bpy.ops.object.join()
    body.name = f"SKM_{name}"
    body.data.name = f"SKM_{name}"
    mod = body.modifiers.new("Armature", "ARMATURE")
    mod.object = arm
    body.parent = arm

    body.data.materials[0].name = f"M_{name}_Body"
    report["skm_tris"] = len(body.data.polygons)
    add_dent_shape_keys(body, length, width, height)
    export_fbx([arm, body], os.path.join(out_dir, f"SKM_{name}.fbx"), True)

    # The M1 profile uses LOD 1 (about 120 k triangles), generated by
    # Unreal's skeletal mesh reduction on import: Blender's collapse breaks
    # the shading of these noisy Tripo surfaces at that ratio.
    report["m1_lod"] = "generated in Unreal (LOD 1, 120 k triangles)"

    for g in glass_objs:
        export_fbx([g], os.path.join(out_dir, f"{g.name}.fbx"), False)
    report["glass_tris"] = {g.name: len(g.data.polygons) for g in glass_objs}

    with open(os.path.join(out_dir, "report.json"), "w") as f:
        json.dump(report, f, indent=2)
    log("done", out_dir)


if __name__ == "__main__":
    main()
