"""Copy City Sample's vehicle base class (Epic code, two files) into a small local plugin, out of
Git, so City Sample's car Blueprints load in our project as they are (docs/gameplay/traffic-mass.md).
Plain Python, editor closed.

    python tools/vehicles/copy_citysample_vehicle_base.py --src <CitySample> --project <project>/GranTheftPraline

City Sample's car Blueprints (BP_vehicle and its children, which MassTraffic's configs and spawners
use) derive from ACitySampleMassVehicleBase, a class of City Sample's game module "CitySample". Its
two files (CitySampleMassVehicleBase.h and .cpp) are copied verbatim into
    <project>/Plugins/CitySampleVehicleBase/Source/CitySample/<their folder in City Sample>
in a runtime module also named CitySample, so the class keeps its path
/Script/CitySample.CitySampleMassVehicleBase: no redirect, no code of ours for the class. The script
writes only the plugin descriptor, the module rules and a one-line module file.

Checked before anything is written (exit code 1, nothing written):
- Plugins/Traffic/Traffic.uplugin is in the project (the class uses MassTraffic);
- the two files are found under <CitySample>/Source/CitySample;
- no quoted #include of the two files names another file of City Sample's own source (else the
  class needs more of the game module: listed in the report).
Epic's files already in the plugin are left untouched when they differ (warning). Report:
<project>/Saved/CitySampleCopy/vehicle_base_report.json (md5 of the copied files, includes).
"""

import argparse
import hashlib
import json
import os
import re
import shutil
import sys

PLUGIN = "CitySampleVehicleBase"
MODULE = "CitySample"
FILES = ("CitySampleMassVehicleBase.h", "CitySampleMassVehicleBase.cpp")
GENERATED = "Generated by tools/vehicles/copy_citysample_vehicle_base.py (Gran Theft Praline), not Epic code."

UPLUGIN = {
    "FileVersion": 3,
    "Version": 1,
    "VersionName": "1.0",
    "FriendlyName": "City Sample vehicle base (local copy)",
    "Description": "City Sample's ACitySampleMassVehicleBase, copied out of Git. " + GENERATED,
    "Category": "Gran Theft Praline",
    "EnabledByDefault": True,
    "CanContainContent": False,
    "Modules": [{"Name": MODULE, "Type": "Runtime", "LoadingPhase": "Default"}],
    "Plugins": [{"Name": "MassGameplay", "Enabled": True}, {"Name": "Traffic", "Enabled": True}],
}

BUILD_CS = """// {generated}
using UnrealBuildTool;

public class {module} : ModuleRules
{{
	public {module}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;
		PublicIncludePaths.Add(ModuleDirectory);
{include_paths}		PublicDependencyModuleNames.AddRange(new string[]
		{{
			"Core", "CoreUObject", "Engine", "MassEntity", "MassCommon", "MassActors", "MassTraffic"
		}});
	}}
}}
"""

MODULE_CPP = """// {generated}
#include "Modules/ModuleManager.h"

IMPLEMENT_MODULE(FDefaultModuleImpl, {module})
"""

INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)


def md5(path):
    with open(path, "rb") as f:
        return hashlib.md5(f.read()).hexdigest()


def find_sources(module_root):
    found = {}
    for folder, _, names in os.walk(module_root):
        for name in names:
            if name in FILES and name not in found:
                found[name] = os.path.join(folder, name)
    return found


def local_includes(path, module_root, own):
    """Quoted includes of path that resolve to another file of City Sample's game module."""
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        text = f.read()
    listed, foreign = [], []
    all_files = None
    for inc in INCLUDE.findall(text):
        listed.append(inc)
        if inc.endswith(".generated.h") or os.path.basename(inc) in own:
            continue
        if os.path.exists(os.path.join(os.path.dirname(path), inc)) or os.path.exists(os.path.join(module_root, inc)):
            foreign.append(inc)
            continue
        if all_files is None:
            all_files = [os.path.relpath(os.path.join(d, n), module_root).replace(os.sep, "/")
                         for d, _, names in os.walk(module_root) for n in names]
        if any(f == inc or f.endswith("/" + inc) for f in all_files):
            foreign.append(inc)
    return listed, foreign


def write_if_changed(path, text, report):
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        report["written"].append(os.path.relpath(path, report["_project"]).replace(os.sep, "/"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True, help="City Sample project folder (holds Source/CitySample)")
    ap.add_argument("--project", required=True, help="our project folder (holds GranTheftPraline.uproject)")
    args = ap.parse_args()
    report = {"plugin": "Plugins/" + PLUGIN, "module": MODULE, "files": {}, "written": [], "warnings": [],
              "_project": args.project}
    out_dir = os.path.join(args.project, "Saved", "CitySampleCopy")

    def finish(result, code):
        report["result"] = result
        report.pop("_project", None)
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "vehicle_base_report.json"), "w") as f:
            json.dump(report, f, indent=2)
        print(json.dumps(report, indent=2))
        sys.exit(code)

    if not os.path.exists(os.path.join(args.project, "Plugins", "Traffic", "Traffic.uplugin")):
        finish("blocked: copy City Sample's Plugins/Traffic first", 1)
    module_root = os.path.join(args.src, "Source", MODULE)
    sources = find_sources(module_root)
    missing = [n for n in FILES if n not in sources]
    if missing:
        finish("blocked: not found under Source/%s: %s" % (MODULE, ", ".join(missing)), 1)
    foreign_all = []
    for name in FILES:
        listed, foreign = local_includes(sources[name], module_root, FILES)
        rel = os.path.relpath(sources[name], module_root).replace(os.sep, "/")
        report["files"][name] = {"from": "Source/%s/%s" % (MODULE, rel), "md5": md5(sources[name]),
                                 "includes": listed, "includes_from_city_sample": foreign}
        foreign_all += foreign
    if foreign_all:
        finish("blocked: the class needs other files of City Sample's game module: " + ", ".join(sorted(set(foreign_all))), 1)

    plugin_dir = os.path.join(args.project, "Plugins", PLUGIN)
    dst_root = os.path.join(plugin_dir, "Source", MODULE)
    folders = set()
    for name in FILES:
        rel = os.path.relpath(sources[name], module_root)
        folders.add(os.path.dirname(rel))
        dst = os.path.join(dst_root, rel)
        if os.path.exists(dst) and md5(dst) != md5(sources[name]):
            report["warnings"].append("%s differs from City Sample's copy, left as is" % name)
            continue
        if not os.path.exists(dst):
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(sources[name], dst)
            report["written"].append(os.path.relpath(dst, args.project).replace(os.sep, "/"))
    include_paths = "".join('\t\tPublicIncludePaths.Add(System.IO.Path.Combine(ModuleDirectory, "%s"));\n' % f.replace(os.sep, "/")
                            for f in sorted(folders) if f)
    write_if_changed(os.path.join(plugin_dir, PLUGIN + ".uplugin"), json.dumps(UPLUGIN, indent="\t") + "\n", report)
    write_if_changed(os.path.join(dst_root, MODULE + ".Build.cs"),
                     BUILD_CS.format(generated=GENERATED, module=MODULE, include_paths=include_paths), report)
    write_if_changed(os.path.join(dst_root, PLUGIN + "Module.cpp"),
                     MODULE_CPP.format(generated=GENERATED, module=MODULE), report)
    finish("ready: rebuild the editor and game targets" if report["written"] else "already in place", 0)


if __name__ == "__main__":
    main()
