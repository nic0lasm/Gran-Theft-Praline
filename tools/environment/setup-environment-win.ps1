<#
.SYNOPSIS
    Windows twin of setup-environment-mac.sh, step 2 only: creates the weather assets in the
    editor (tools/environment/unreal/setup_environment.py), so that a Windows package has the
    rain layer, the cloud dome and the light function cloud shadow.

.DESCRIPTION
    Creates under GranTheftPraline/Content/Environment/Weather (not in Git, about 2 MB):
    MPC_Environment, T_RainStreaks, T_PuddleNoise, SM_RainLayer, M_RainLayer, SM_CloudDome,
    M_CloudDome, M_CloudShadowLF. Everything is generated by the script (procedural textures,
    copies of engine shapes): nothing is downloaded, no pack is needed.
    Existing assets are not modified (GTP_ENV_WET stays off: street materials untouched), the map
    is not opened or saved. The volumetric clouds themselves are the map's VolumetricCloud actor
    with the engine material; this script does not touch them.
    Not done here: the night lights file (build_night_lights.py needs the city pipeline outputs).

    Run from the root of the clone, no Unreal running:
        powershell -ExecutionPolicy Bypass -File tools\environment\setup-environment-win.ps1
    UE_ROOT overrides the engine folder (default C:\Program Files\Epic Games\UE_5.8).
    Result: GranTheftPraline\Saved\Environment\setup_report.json ("errors": [] expected; it also
    lists the scalar parameters of the engine cloud material, to check CloudCoverageParameters).
    Then package as usual (tools/build/package-win.ps1).
#>
$ErrorActionPreference = 'Stop'

$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$project = Join-Path $repo 'GranTheftPraline\GranTheftPraline.uproject'
$ueRoot = if ($env:UE_ROOT) { $env:UE_ROOT } else { 'C:\Program Files\Epic Games\UE_5.8' }
$editorCmd = Join-Path $ueRoot 'Engine\Binaries\Win64\UnrealEditor-Cmd.exe'
$script = Join-Path $repo 'tools\environment\unreal\setup_environment.py'
$launcher = Join-Path $repo 'GranTheftPraline\Content\Python\gtp_run.py'
$report = Join-Path $repo 'GranTheftPraline\Saved\Environment\setup_report.json'

if (-not (Test-Path $editorCmd)) { throw "Unreal Editor not found: $editorCmd" }
if (-not (Test-Path $launcher)) { throw "Content/Python/gtp_run.py missing" }
if (Get-Process -Name 'UnrealEditor*', 'GranTheftPraline*' -ErrorAction SilentlyContinue) {
    throw 'an Unreal process is already running, wait for it to finish'
}
if (Test-Path $report) { Remove-Item $report }

# The clone path has a space: gtp_run.py (Content/Python) runs the script named by GTP_PY_SCRIPT.
$env:GTP_PY_SCRIPT = $script
$env:GTP_ENV_WET = 'off'
& $editorCmd $project -unattended -nosplash -nosound "-ExecutePythonScript=__import__('gtp_run').main()"
Write-Host "editor exit code: $LASTEXITCODE"

if (-not (Test-Path $report)) { throw 'setup_environment.py wrote no report' }
Get-Content $report
$json = Get-Content $report -Raw | ConvertFrom-Json
if ($json.errors.Count -gt 0) { throw "setup_environment.py reported errors" }
Write-Host 'weather assets ready, package now'
