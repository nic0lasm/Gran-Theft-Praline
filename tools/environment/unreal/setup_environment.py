"""Create the day-night and weather assets inside the Unreal Editor (no UI).

Run with tools/environment/setup-environment-mac.sh (copies this script to a
path without spaces, as the other editor scripts). Idempotent.

Creates under /Game/Environment/Weather (kept out of Git, regenerated here):
  MPC_Environment   parameter collection written by GTPEnvironmentSubsystem:
                    Wetness, Puddles, RainIntensity, CityLights, EmissiveScale,
                    Cloudiness, TimeOfDay
  T_RainStreaks     procedural streaks (tools/environment/textures.py)
  T_PuddleNoise     procedural tileable noise for the puddle mask
  SM_RainLayer      copy of the engine cylinder, the rain layer around the camera
  M_RainLayer       translucent lit rain, opacity = streaks x RainIntensity
  SM_CloudDome      copy of the engine sphere, M_CloudDome unlit 2D clouds: the cheap
                    fallback of the volumetric clouds (bCloudDome of a light budget)
  M_CloudShadowLF   light function of the sun: cheap drifting cloud shadows
                    (bCloudShadowLightFunction, -Sky=lightfunction)

The wet look and the night emissive belong to the material generators of the
city and asset tools, which call gtp_weather.add_weather() (same folder). As a
stopgap, GTP_ENV_WET=on patches the existing street materials directly
(art bible section 4, wet surfaces):
  - base colour darkened and roughness lowered with Wetness (less on walls);
  - puddles on flat ground with Puddles (near-mirror roughness);
  - emissive multiplied by EmissiveScale (shop windows and signs brighter at night).
Each patched material gets the metadata tag GTPWeather=1 and is skipped next
time; a material regenerated by the city pipeline loses the tag and is patched
again on the next run (run this after tools/city/unreal/run_city_import.sh).

Report: GranTheftPraline/Saved/Environment/setup_report.json (with the scalar
parameters of the engine cloud material, to check CloudCoverageParameters in
DefaultGame.ini).
"""

import json
import os
import sys

import unreal

PROJECT = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
REPO = os.path.abspath(os.path.join(PROJECT, ".."))
sys.path.insert(0, os.path.join(REPO, "tools", "environment"))
import textures  # noqa: E402

sys.path.insert(0, os.path.join(REPO, "tools", "environment", "unreal"))
import gtp_weather  # noqa: E402

Graph = gtp_weather.Graph

FOLDER = "/Game/Environment/Weather"
MPC_PATH = FOLDER + "/MPC_Environment"
CLOUD_MATERIAL = "/Engine/EngineSky/VolumetricClouds/m_SimpleVolumetricCloud_Inst"
ENGINE_CYLINDER = "/Engine/BasicShapes/Cylinder"
ENGINE_SPHERE = "/Engine/BasicShapes/Sphere"
SAVED = os.path.join(PROJECT, "Saved", "Environment")

# Street materials that get wet (name, roles); found anywhere under /Game.
WET_MATERIALS = {
    "M_City_Ground": ("wet", "puddles"),
    "M_City_Shell": ("wet",),
    "M_City_Kit": ("wet", "emissive"),
    "M_Master_Surface": ("wet",),
    "M_Sign_Fascia": ("emissive",),
}
eal = unreal.EditorAssetLibrary
mel = unreal.MaterialEditingLibrary
asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
report = {"errors": [], "created": [], "patched": [], "skipped": []}


def log(msg):
    unreal.log_warning("[Environment] " + msg)


def load_or_create(name, cls, factory):
    path = FOLDER + "/" + name
    if eal.does_asset_exist(path):
        return eal.load_asset(path), False
    asset = asset_tools.create_asset(name, FOLDER, cls, factory)
    report["created"].append(path)
    return asset, True


# --------------------------------------------------------------------------- assets

def parameter_collection():
    if not eal.does_asset_exist(MPC_PATH):
        report["created"].append(MPC_PATH)
    return gtp_weather.collection()


def texture(name, generator):
    path = FOLDER + "/" + name
    if not eal.does_asset_exist(path):
        report["created"].append(path)
    return gtp_weather.texture(name, generator)


def rain_mesh():
    path = FOLDER + "/SM_RainLayer"
    if not eal.does_asset_exist(path):
        eal.duplicate_asset(ENGINE_CYLINDER, path)
        eal.save_asset(path, only_if_is_dirty=False)   # a duplicate lives only in memory until saved
        report["created"].append(path)
    mesh = eal.load_asset(path)
    return mesh


def cloud_dome_mesh():
    path = FOLDER + "/SM_CloudDome"
    if not eal.does_asset_exist(path):
        eal.duplicate_asset(ENGINE_SPHERE, path)
        eal.save_asset(path, only_if_is_dirty=False)   # a duplicate lives only in memory until saved
        report["created"].append(path)
    return eal.load_asset(path)


def cloud_dome_material(mpc, noise):
    """Unlit 2D clouds seen from inside a large sphere: noise above 1 - Cloudiness, slow drift,
    luminance CloudLuminance (set from the exposure by the game). At night (CityLights) the
    underside takes the orange of the city lights, like a real overcast night over a town.
    The graph is rebuilt on every run so an older version on disk is replaced."""
    mat, created = load_or_create("M_CloudDome", unreal.Material, unreal.MaterialFactoryNew())
    if not created:
        mel.delete_all_material_expressions(mat)
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    mat.set_editor_property("two_sided", True)
    g = Graph(mat)
    layers = []
    for tiling, speed in (((5.0, 2.5), 0.004), ((11.0, 5.5), 0.007)):
        uv = g.node(unreal.MaterialExpressionTextureCoordinate, u_tiling=tiling[0], v_tiling=tiling[1])
        pan = g.node(unreal.MaterialExpressionPanner, speed_x=speed, speed_y=0.0)
        g.link(uv, pan, "Coordinate")
        tex = g.node(unreal.MaterialExpressionTextureSample, texture=noise,
                     sampler_type=unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
        g.link(pan, tex, "UVs")
        layers.append(tex)
    detail = g.lerp(layers[0], layers[1], 0.35, a_out="R", b_out="R")
    level = g.node(unreal.MaterialExpressionSubtract)
    g.link(detail, level, "A")
    g.link(g.lerp(1.0, 0.0, g.collection(mpc, "Cloudiness")), level, "B")
    opacity = g.mul(g.saturate(g.mul(level, 3.0)), 0.95)
    mel.connect_material_property(opacity, "", unreal.MaterialProperty.MP_OPACITY)
    shade = g.lerp(0.75, 1.0, detail)  # thicker parts a little darker underneath
    lum = g.mul(g.collection(mpc, "CloudLuminance"), shade)
    white = g.node(unreal.MaterialExpressionConstant3Vector, constant=unreal.LinearColor(1.0, 1.0, 1.0, 1.0))
    sodium = g.node(unreal.MaterialExpressionConstant3Vector, constant=unreal.LinearColor(1.0, 0.62, 0.38, 1.0))
    glow = g.lerp(white, sodium, g.mul(g.collection(mpc, "CityLights"), 0.7))
    tinted = g.mul(lum, glow)
    mel.connect_material_property(tinted, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat)
    return mat


def cloud_shadow_material(mpc, noise):
    """Light function of the sun: drifting cloud shadows from two octaves of noise on the
    ground plane. Parameters set per weather by GTPEnvironmentSubsystem (MID):
    Coverage (share of ground under cloud), Strength (sun removed under a cloud),
    Mean (multiplier of the whole function), Contrast (edge sharpness).
    light = Mean * (1 - Strength * saturate((density - (1 - Coverage)) * Contrast))
    The graph is rebuilt on every run so an older version on disk is replaced."""
    mat, created = load_or_create("M_CloudShadowLF", unreal.Material, unreal.MaterialFactoryNew())
    if not created:
        mel.delete_all_material_expressions(mat)
    mat.set_editor_property("material_domain", unreal.MaterialDomain.MD_LIGHT_FUNCTION)
    g = Graph(mat)

    def param(name, value):
        return g.node(unreal.MaterialExpressionScalarParameter, parameter_name=name, default_value=value)

    pos = g.node(unreal.MaterialExpressionWorldPosition)
    xy = g.node(unreal.MaterialExpressionComponentMask, r=True, g=True, b=False, a=False)
    g.link(pos, xy)
    layers = []
    for tile_cm, speed in ((250000.0, 0.0006), (90000.0, 0.0011)):
        uv = g.mul(xy, 1.0 / tile_cm)
        pan = g.node(unreal.MaterialExpressionPanner, speed_x=speed, speed_y=speed * 0.4)
        g.link(uv, pan, "Coordinate")
        tex = g.node(unreal.MaterialExpressionTextureSample, texture=noise,
                     sampler_type=unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
        g.link(pan, tex, "UVs")
        layers.append(tex)
    density = g.lerp(layers[0], layers[1], 0.35, a_out="R", b_out="R")
    level = g.node(unreal.MaterialExpressionSubtract)
    g.link(density, level, "A")
    g.link(g.lerp(1.0, 0.0, param("Coverage", 0.3)), level, "B")
    cover = g.saturate(g.mul(level, param("Contrast", 3.0)))
    loss = g.mul(cover, param("Strength", 0.75))
    keep = g.node(unreal.MaterialExpressionOneMinus)
    g.link(loss, keep)
    light = g.mul(keep, param("Mean", 1.0))
    mel.connect_material_property(light, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat)
    return mat


def rain_material(mpc, streaks):
    mat, created = load_or_create("M_RainLayer", unreal.Material, unreal.MaterialFactoryNew())
    if not created:
        return mat
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("two_sided", True)
    mat.set_editor_property("translucency_lighting_mode",
                            unreal.TranslucencyLightingMode.TLM_VOLUMETRIC_NON_DIRECTIONAL)
    g = Graph(mat)
    layers = []
    for tiling, speed in (((6.0, 3.0), 1.3), ((9.0, 5.0), 1.9)):
        uv = g.node(unreal.MaterialExpressionTextureCoordinate, u_tiling=tiling[0], v_tiling=tiling[1])
        pan = g.node(unreal.MaterialExpressionPanner, speed_x=0.0, speed_y=speed)
        g.link(uv, pan, "Coordinate")
        tex = g.node(unreal.MaterialExpressionTextureSample, texture=streaks,
                     sampler_type=unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
        g.link(pan, tex, "UVs")
        layers.append(tex)
    add = g.node(unreal.MaterialExpressionAdd)
    g.link(layers[0], add, "A", "R")
    g.link(layers[1], add, "B", "R")
    rain = g.collection(mpc, "RainIntensity")
    opacity = g.mul(g.mul(add, rain), 0.35)
    fade = g.node(unreal.MaterialExpressionDepthFade, fade_distance_default=150.0)
    g.link(opacity, fade, "Opacity")
    mel.connect_material_property(fade, "", unreal.MaterialProperty.MP_OPACITY)
    base = g.node(unreal.MaterialExpressionConstant3Vector, constant=unreal.LinearColor(0.7, 0.72, 0.75, 1.0))
    mel.connect_material_property(base, "", unreal.MaterialProperty.MP_BASE_COLOR)
    rough = g.node(unreal.MaterialExpressionConstant, r=0.2)
    mel.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat)
    return mat


# --------------------------------------------------------------------------- wet materials

def patch_material(mat, roles, mpc, puddle_tex):
    gtp_weather.add_weather(mat, roles, mpc, puddle_tex)
    mel.recompile_material(mat)
    eal.save_loaded_asset(mat)


def patch_street_materials(mpc, puddle_tex):
    if os.environ.get("GTP_ENV_WET", "off") != "on":
        return
    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    found = registry.get_assets_by_class(unreal.TopLevelAssetPath("/Script/Engine", "Material"), True)
    for data in found:
        name = str(data.asset_name)
        path = str(data.package_name)
        if name not in WET_MATERIALS or not path.startswith("/Game/"):
            continue
        mat = eal.load_asset(path)
        if eal.get_metadata_tag(mat, "GTPWeather") == "1":
            report["skipped"].append(path)
            continue
        try:
            patch_material(mat, WET_MATERIALS[name], mpc, puddle_tex)
            report["patched"].append(path)
        except Exception as exc:  # keep going, the report lists it
            report["errors"].append("%s: %s" % (path, exc))
    missing = sorted(set(WET_MATERIALS) - {os.path.basename(p) for p in report["patched"] + report["skipped"]})
    report["materials_not_found"] = missing


def cloud_parameters():
    if not eal.does_asset_exist(CLOUD_MATERIAL):
        return None
    mi = eal.load_asset(CLOUD_MATERIAL)
    try:
        return [str(n) for n in mel.get_scalar_parameter_names(mi)]
    except Exception as exc:
        return ["error: %s" % exc]


def check_on_disk():
    """Every asset of the folder must be a .uasset on disk, or the package will miss it."""
    content = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_content_dir())
    for name in ("MPC_Environment", "T_RainStreaks", "T_PuddleNoise", "SM_RainLayer", "M_RainLayer",
                 "SM_CloudDome", "M_CloudDome", "M_CloudShadowLF"):
        rel = (FOLDER + "/" + name).replace("/Game/", "", 1) + ".uasset"
        if not os.path.isfile(os.path.join(content, rel)):
            report["errors"].append("not saved on disk: " + rel)


def main():
    try:
        mpc = parameter_collection()
        streaks = texture("T_RainStreaks", textures.rain_streaks)
        puddles = texture("T_PuddleNoise", textures.puddle_noise)
        rain_mesh()
        rain_material(mpc, streaks)
        cloud_dome_mesh()
        cloud_dome_material(mpc, puddles)
        cloud_shadow_material(mpc, puddles)
        patch_street_materials(mpc, puddles)
        report["cloud_material_scalar_parameters"] = cloud_parameters()
        check_on_disk()
    except Exception as exc:
        report["errors"].append(str(exc))
    os.makedirs(SAVED, exist_ok=True)
    with open(os.path.join(SAVED, "setup_report.json"), "w") as f:
        json.dump(report, f, indent=2)
    log("done: %d created, %d patched, %d errors" % (len(report["created"]), len(report["patched"]),
                                                    len(report["errors"])))


main()
